#!/usr/bin/env python3
"""Tier-A offline replay: test checker decisions and pilot rules on recorded Agent runs in minutes, not days.

Usage:
    replay.py run scenarios/velocity_swaps.yaml [--only NAME ...] [--workers 16]
    replay.py rescore [--only NAME ...]
    replay.py summary

``run`` replays each scenario (see replay_lib.run_scenario) and writes one JSON record per scenario to
outputs/records/<name>.json; ``summary`` collects every record into outputs/summary.md: per scenario the
compare verdict the Agent would have seen, whether the references agree, and for each pilot rule
whether the pilot reached the same verdict and how well it predicted the full-catalog depth and time bias.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OUT = HERE / "outputs"
sys.path.insert(0, str(HERE))


def cmd_run(args) -> int:
    from replay_lib import run_scenario
    spec = yaml.safe_load(Path(args.scenarios).read_text())
    defaults = spec.get("defaults", {})
    (OUT / "records").mkdir(parents=True, exist_ok=True)
    for sc in spec["scenarios"]:
        sc = {**defaults, **sc}
        if args.only and sc["name"] not in args.only:
            continue
        t = time.time()
        try:
            rec = run_scenario(sc, OUT, workers=args.workers, log=lambda m: print(m, flush=True))
        except Exception as exc:  # keep going; the failure is recorded
            rec = {"name": sc["name"], "error": f"{type(exc).__name__}: {exc}"}
            print(f"[{sc['name']}] FAILED: {rec['error']}", flush=True)
        rec["finished_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        (OUT / "records" / f"{sc['name']}.json").write_text(json.dumps(rec, indent=1, default=str) + "\n")
        print(f"[{sc['name']}] done in {time.time() - t:.0f} s", flush=True)
    return cmd_summary(args)


def cmd_rescore(args) -> int:
    from replay_lib import rescore
    for p in sorted((OUT / "records").glob("*.json")):
        rec = json.loads(p.read_text())
        if "error" in rec or (args.only and rec["name"] not in args.only):
            continue
        p.write_text(json.dumps(rescore(rec), indent=1, default=str) + "\n")
        print(f"rescored {rec['name']}", flush=True)
    return cmd_summary(args)


def _f(v, fmt="+.2f"):
    return "—" if v is None else format(v, fmt)


def cmd_summary(args) -> int:
    recs = [json.loads(p.read_text()) for p in sorted((OUT / "records").glob("*.json"))]
    lines = ["# Replay summary", "", "Generated by `replay.py summary`. Agent view: compare verdict on the full candidate. "
             "Benchmark view: the trusted-catalog criteria in the dimensions the change can affect.", "",
             "| scenario | change | compare verdict | improved / worsened | references | agreement | failed before → after | dz before → after (km) | cost (min) |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in recs:
        if "error" in r:
            lines.append(f"| {r['name']} | — | error: {r['error'][:80]} | | | | | | |")
            continue
        a, b = r["agent_view"], r["benchmark_view"]
        tr = b["truth"]
        lines.append(f"| {r['name']} | {r['change']} | {a['verdict']} | {', '.join(a['improved']) or '—'} / {', '.join(a['worsened']) or '—'} | "
                     f"{tr['label']} | {b['agreement']} | {', '.join(tr['failed_before']) or 'none'} → {', '.join(tr['failed_after']) or 'none'} | "
                     f"{_f(b['before']['values']['dz_final_km'])} → {_f(b['after']['values']['dz_final_km'])} | {r['cost_s']['total'] / 60:.0f} |")
    pil = [(r, p) for r in recs if "error" not in r for p in r.get("pilots", [])]
    if pil:
        lines += ["", "## Pilot transfer", "", "Pilot: the same intervention on a subset only, checked and compared the same way. "
                  "Predicted bias = the run's bias + the median change of the pilot events (no reference needed for the change).", "",
                  "| scenario | rule | events | pilot verdict | full verdict | same | predicted dz | actual dz | predicted dt | actual dt | cost (min) |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r, p in pil:
            lines.append(f"| {r['name']} | {p['rule']} | {p['events']} | {p['verdict']} | {r['agent_view']['verdict']} | {'yes' if p['same_verdict_as_full'] else 'no'} | "
                         f"{_f(p['predicted']['dz_final_km'])} | {_f(p['actual']['dz_final_km'])} | {_f(p['predicted']['time_bias_final_s'])} | "
                         f"{_f(p['actual']['time_bias_final_s'])} | {p['cost_s'] / 60:.1f} |")
    (OUT / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("scenarios")
    r.add_argument("--only", nargs="*")
    r.add_argument("--workers", type=int, default=16)
    r.set_defaults(func=cmd_run)
    rs = sub.add_parser("rescore", help="recompute the benchmark view of every record from its cached catalogs")
    rs.add_argument("--only", nargs="*")
    rs.set_defaults(func=cmd_rescore)
    s = sub.add_parser("summary")
    s.set_defaults(func=cmd_summary)
    args = p.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
