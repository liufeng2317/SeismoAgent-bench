"""HypoDD grid workflow: build ``hypoDD_*.inp``, run the binary per grid, merge catalogs and residuals.

Uses :class:`Run_HypoDD` with PyTorch :class:`~torch.utils.data.Dataset` for parallel grid jobs,
plus helpers to merge outputs and summarize relocation quality.
"""
