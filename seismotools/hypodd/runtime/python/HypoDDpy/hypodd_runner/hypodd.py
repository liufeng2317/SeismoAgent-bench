def _native_log_candidates(output_folder):
    patterns = (
        "*.log",
        "*.err",
        "*.out",
        "*.stderr",
        "hypoDD*",
        "ph2dt*",
    )
    hits = []
    for pat in patterns:
        hits.extend(glob.glob(os.path.join(output_folder, pat)))
    hits = sorted({p for p in hits if os.path.isfile(p)})
    return hits[:8]


def _read_merged_hypodd_catalog(ctlg_code, output_folder, suffix, label):
    ctlg_file = os.path.join(output_folder, f"{ctlg_code}.{suffix}")
    logs = _native_log_candidates(output_folder)
    log_hint = ", ".join(os.path.basename(p) for p in logs) if logs else "no log-like files found"
    evidence_hint = (
        "Inspect native evidence in this same output directory before changing "
        "parameters or inputs: hypoDD/ph2dt logs, hypoDD_*-*.inp, dt_*.ct, "
        "hypoDD_phase_*.dat, hypoDD_*.loc, hypoDD_*.reloc, hypoDD_*.src, "
        "and hypoDD_*.sta. Do not infer MAXEVE/MAXDATA, reduce events, alter "
        "phase parsing, or tune ph2dt/HypoDD parameters from this message alone; "
        "use the native log text as the cause."
    )
    if not os.path.exists(ctlg_file):
        raise NativeOutputError(
            f"Missing HypoDD native {label} catalog: {ctlg_file}. "
            "This file must be produced by the ph2dt/HypoDD pipeline; do not "
            f"create {ctlg_code}.csv as a substitute. Native evidence candidates: "
            f"{log_hint}. {evidence_hint}"
        )
    if os.path.getsize(ctlg_file) == 0:
        raise NativeOutputError(
            f"Empty HypoDD native {label} catalog: {ctlg_file}. "
            "HypoDD produced the expected catalog path but no valid catalog rows. "
            "This is a native-output failure, not by itself a config/schema error "
            "or an event-count-limit error. Do not treat placeholder CSV files as "
            f"success. Native evidence candidates: {log_hint}. {evidence_hint}"
        )
    try:
        catalog = pd.read_csv(ctlg_file, sep=",", header=None)
    except pd.errors.EmptyDataError as exc:
        raise NativeOutputError(
            f"HypoDD native {label} catalog has no parseable rows: {ctlg_file}. "
            "HypoDD produced a catalog file but it contains no parseable rows. "
            "This message alone does not identify the scientific/native cause. "
            f"Native evidence candidates: {log_hint}. {evidence_hint}"
        ) from exc
    if catalog.empty or catalog.shape[1] < 5:
        raise NativeOutputError(
            f"HypoDD native {label} catalog is invalid: {ctlg_file}; "
            f"rows={len(catalog)}, columns={catalog.shape[1]}. Expected at least "
            "five columns: ot, lat, lon, dep, mag. This message only reports "
            "invalid native output shape; inspect the native evidence to determine "
            f"the cause. Native evidence candidates: {log_hint}. {evidence_hint}"
        )
    catalog = catalog.iloc[:, :5].copy()
    catalog.columns = ["ot", "lat", "lon", "dep", "mag"]
    catalog["ot"] = catalog["ot"].apply(lambda x: UTCDateTime(x))
    catalog["lat"] = catalog["lat"].apply(lambda x: float(x))
    catalog["lon"] = catalog["lon"].apply(lambda x: float(x))
    catalog["dep"] = catalog["dep"].apply(lambda x: float(x))
    catalog["mag"] = catalog["mag"].apply(lambda x: float(x))
    return catalog


def load_hypodd_original_catalog(ctlg_code, output_folder):
    """
    Load hypoDD output files (raw location catalog).
    
    Parameters
    ----------
    ctlg_code : str
        Prefix for output catalog/phase files.
    output_folder : str
        Directory containing the merged ``{ctlg_code}.loc`` file.
        
    Returns
    -------
    catalog : pandas.DataFrame
        Catalog dataframe with columns: 'ot', 'lat', 'lon', 'dep', 'mag'.
        
    """
    return _read_merged_hypodd_catalog(ctlg_code, output_folder, "loc", "original")

